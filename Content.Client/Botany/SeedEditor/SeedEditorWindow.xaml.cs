/// <summary>
/// Admin window to pick a plant species, edit everything about its seed and get a packet of it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SeedEditorWindow : FancyWindow
{
    [Dependency] private IComponentFactory _factory = default!;
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPrototypeManager _prototypeManager = default!;

    private readonly SeedEditorSystem _seedEditor;
    private SeedEditorData? _data;

    /// <summary>
    /// Raised when the user asks for a seed packet of the edited seed.
    /// </summary>
    public event Action<SeedEditorData>? OnSpawnSeed;

    /// <summary>
    /// Raised when the editor needs the default data of a species, which comes from the server.
    /// </summary>
    public event Action<EntProtoId>? OnRequestSpecies;

    private static readonly Color ValidColor = Color.LimeGreen;
    private static readonly Color InvalidColor = Color.FromHex("#e05050");

    public SeedEditorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _seedEditor = _entityManager.System<SeedEditorSystem>();

        SpeciesSearch.OnTextChanged += _ => PopulateSpecies();
        SpeciesList.OnItemSelected += args =>
        {
            if (args.ItemList[args.ItemIndex].Metadata is EntProtoId species)
                OnRequestSpecies?.Invoke(species);
        };
        ResetButton.OnPressed += _ =>
        {
            if (_data != null)
                OnRequestSpecies?.Invoke(_data.Species);
        };
        SpawnButton.OnPressed += _ =>
        {
            if (_data != null)
                OnSpawnSeed?.Invoke(_data);
        };

        PopulateSpecies();
    }

    /// <summary>
    /// Shows a seed in the editor.
    /// </summary>
    public void LoadData(SeedEditorData data)
    {
        _data = data;
        SpeciesName.Text = SpeciesTitle(data.Species);
        ResultLabel.Visible = false;
        ResetButton.Disabled = false;
        SpawnButton.Disabled = false;
        RebuildSections();
    }

    /// <summary>
    /// Shows whether the last seed packet was made.
    /// </summary>
    public void ShowResult(string? error)
    {
        ResultLabel.Visible = true;
        ResultLabel.Text = error ?? Loc.GetString("seed-editor-spawned");
        ResultLabel.FontColorOverride = error == null ? ValidColor : InvalidColor;
    }

    private void PopulateSpecies()
    {
        var filter = SpeciesSearch.Text.Trim();
        var species = new List<(string Text, EntProtoId Id)>();
        foreach (var proto in _prototypeManager.EnumeratePrototypes<EntityPrototype>())
        {
            if (proto.Abstract
                || !proto.TryGetComponent<PlantComponent>(out _, _factory)
                || !proto.TryGetComponent<PlantDataComponent>(out _, _factory))
                continue;

            var text = SpeciesTitle(proto.ID);
            if (filter.Length == 0 || text.Contains(filter, StringComparison.CurrentCultureIgnoreCase))
                species.Add((text, proto.ID));
        }

        SpeciesList.Clear();
        foreach (var (text, id) in species.OrderBy(s => s.Text, StringComparer.CurrentCultureIgnoreCase))
        {
            SpeciesList.Add(new ItemList.Item(SpeciesList) { Text = text, Metadata = id });
        }
    }

    private string SpeciesTitle(EntProtoId species)
    {
        return _prototypeManager.TryIndex(species, out var proto)
            && proto.TryGetComponent<PlantDataComponent>(out var plantData, _factory)
            ? Loc.GetString("seed-editor-species", ("name", Loc.GetString(plantData.Name)), ("id", species.Id))
            : species.Id;
    }

    private void RebuildSections()
    {
        Sections.RemoveAllChildren();
        if (_data == null)
            return;

        var components = _seedEditor.GetSeedComponents();
        foreach (var registration in components)
        {
            if (_data.Fields.TryGetValue(registration.Name, out var fields))
                AddFieldSection(registration, fields);
        }

        AddTraitSection(_data, components);
        AddChemicalSection(_data);
        AddGasSection(_data);
    }

    private BoxContainer AddSection(string title)
    {
        var section = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
        section.AddChild(new Label { Text = title, StyleClasses = { "LabelKeyText" } });
        Sections.AddChild(section);
        return section;
    }

    private static GridContainer NewGrid(int columns)
    {
        return new GridContainer { Columns = columns, HSeparationOverride = 8, VSeparationOverride = 4 };
    }

    #region Fields

    private void AddFieldSection(ComponentRegistration registration, Dictionary<string, string> fields)
    {
        var section = AddSection(ComponentTitle(registration.Name));
        var grid = NewGrid(4);
        _data!.FieldOptions.TryGetValue(registration.Name, out var componentOptions);
        foreach (var field in fields.Keys.OrderBy(f => f).ToList())
        {
            List<string>? options = null;
            componentOptions?.TryGetValue(field, out options);

            grid.AddChild(new Label { Text = FieldTitle(field), MinWidth = 160 });
            grid.AddChild(FieldEditor(fields, field, options));
        }

        section.AddChild(grid);
    }

    private static Control FieldEditor(Dictionary<string, string> fields, string field, List<string>? options)
    {
        var value = fields[field];

        if (bool.TryParse(value, out var toggled))
        {
            var checkBox = new CheckBox { Pressed = toggled };
            checkBox.OnToggled += args => fields[field] = args.Pressed ? "true" : "false";
            return checkBox;
        }

        if (options != null)
        {
            var optionButton = new OptionButton { MinWidth = 120 };
            for (var i = 0; i < options.Count; i++)
            {
                optionButton.AddItem(options[i], i);
                if (options[i] == value)
                    optionButton.SelectId(i);
            }

            optionButton.OnItemSelected += args =>
            {
                optionButton.SelectId(args.Id);
                fields[field] = options[args.Id];
            };
            return optionButton;
        }

        var edit = new LineEdit { Text = value, MinWidth = 100 };
        edit.OnTextChanged += args => fields[field] = args.Text;
        return edit;
    }

    private static string ComponentTitle(string component)
    {
        return Loc.TryGetString($"seed-editor-component-{component}", out var title) ? title : Humanize(component);
    }

    private static string FieldTitle(string field)
    {
        return Loc.TryGetString($"seed-editor-field-{field}", out var title) ? title : Humanize(field);
    }

    /// <summary>
    /// Turns "waterConsumption" into "Water consumption", for fields without a localized name.
    /// </summary>
    private static string Humanize(string name)
    {
        var words = new System.Text.StringBuilder();
        for (var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (i == 0)
                words.Append(char.ToUpperInvariant(c));
            else if (char.IsUpper(c))
                words.Append(' ').Append(char.ToLowerInvariant(c));
            else
                words.Append(c);
        }

        return words.ToString();
    }

    #endregion

    #region Traits

    private void AddTraitSection(SeedEditorData data, List<ComponentRegistration> components)
    {
        var section = AddSection(Loc.GetString("seed-editor-section-traits"));
        var grid = NewGrid(3);

        var traits = _prototypeManager.EnumeratePrototypes<PlantTraitPrototype>()
            .OrderBy(t => Loc.GetString(t.Name), StringComparer.CurrentCultureIgnoreCase);
        foreach (var trait in traits)
        {
            var text = Capitalize(Loc.GetString(trait.Name));
            if (trait.PollinationProtected)
                text = Loc.GetString("seed-editor-trait-protected", ("trait", text));

            var checkBox = new CheckBox { Text = text, Pressed = data.Traits.Contains(trait.ID) };
            if (trait.Description is { } description)
                checkBox.ToolTip = Loc.GetString(description);

            var traitId = new ProtoId<PlantTraitPrototype>(trait.ID);
            checkBox.OnToggled += args =>
            {
                if (args.Pressed && !data.Traits.Contains(traitId))
                    data.Traits.Add(traitId);
                else if (!args.Pressed)
                    data.Traits.Remove(traitId);
            };
            grid.AddChild(checkBox);
        }

        foreach (var registration in components.Where(SharedSeedEditorSystem.IsTraitComponent))
        {
            var traitName = _factory.GetComponent(registration) is PlantTraitsComponent { TraitName: { } name }
                ? Capitalize(Loc.GetString(name))
                : registration.Name;

            var checkBox = new CheckBox { Text = traitName, Pressed = data.TraitComponents.Contains(registration.Name) };
            checkBox.OnToggled += args =>
            {
                if (args.Pressed)
                    data.TraitComponents.Add(registration.Name);
                else
                    data.TraitComponents.Remove(registration.Name);
            };
            grid.AddChild(checkBox);
        }

        section.AddChild(grid);
    }

    private static string Capitalize(string text)
    {
        return text.Length == 0 ? text : string.Concat(char.ToUpper(text[0]).ToString(), text.Substring(1));
    }

    #endregion

    #region Chemicals

    private void AddChemicalSection(SeedEditorData data)
    {
        var section = AddSection(Loc.GetString("seed-editor-section-chemicals"));
        var grid = NewGrid(5);
        grid.AddChild(new Label { Text = Loc.GetString("seed-editor-chemical-reagent"), MinWidth = 160 });
        grid.AddChild(new Label { Text = Loc.GetString("seed-editor-chemical-min") });
        grid.AddChild(new Label { Text = Loc.GetString("seed-editor-chemical-max") });
        grid.AddChild(new Label { Text = Loc.GetString("seed-editor-chemical-potency-divisor") });
        grid.AddChild(new Control());

        foreach (var reagent in data.Chemicals.Keys.OrderBy(ReagentName).ToList())
        {
            grid.AddChild(new Label { Text = ReagentName(reagent) });
            grid.AddChild(NumberEditor(data.Chemicals[reagent].Min.Float(),
                value => data.Chemicals[reagent] = data.Chemicals[reagent] with { Min = FixedPoint2.New(value) }));
            grid.AddChild(NumberEditor(data.Chemicals[reagent].Max.Float(),
                value => data.Chemicals[reagent] = data.Chemicals[reagent] with { Max = FixedPoint2.New(value) }));
            grid.AddChild(NumberEditor(data.Chemicals[reagent].PotencyDivisor,
                value => data.Chemicals[reagent] = data.Chemicals[reagent] with { PotencyDivisor = value }));
            grid.AddChild(RemoveButton(() => data.Chemicals.Remove(reagent)));
        }

        section.AddChild(grid);

        // Searchable list to add a reagent.
        var search = new LineEdit { PlaceHolder = Loc.GetString("seed-editor-chemical-add") };
        var list = new ItemList { SelectMode = ItemList.ItemListSelectMode.Single, MinHeight = 120 };
        search.OnTextChanged += _ => PopulateReagents(list, search.Text, data);
        list.OnItemSelected += args =>
        {
            if (args.ItemList[args.ItemIndex].Metadata is not ProtoId<ReagentPrototype> reagent)
                return;

            data.Chemicals[reagent] = new SeedEditorChemical(FixedPoint2.New(1), FixedPoint2.New(10), 10);
            RebuildSections();
        };
        PopulateReagents(list, string.Empty, data);
        section.AddChild(search);
        section.AddChild(list);
    }

    private void PopulateReagents(ItemList list, string filter, SeedEditorData data)
    {
        list.Clear();
        filter = filter.Trim();
        var reagents = _prototypeManager.EnumeratePrototypes<ReagentPrototype>()
            .Where(r => !data.Chemicals.ContainsKey(r.ID))
            .Select(r => (Name: r.LocalizedName, r.ID))
            .Where(r => filter.Length == 0
                || r.Name.Contains(filter, StringComparison.CurrentCultureIgnoreCase)
                || r.ID.Contains(filter, StringComparison.OrdinalIgnoreCase))
            .OrderBy(r => r.Name, StringComparer.CurrentCultureIgnoreCase);

        foreach (var (name, id) in reagents)
        {
            list.Add(new ItemList.Item(list) { Text = name, Metadata = new ProtoId<ReagentPrototype>(id) });
        }
    }

    private string ReagentName(ProtoId<ReagentPrototype> reagent)
    {
        return _prototypeManager.TryIndex(reagent, out var proto) ? proto.LocalizedName : reagent.Id;
    }

    #endregion

    #region Gases

    private void AddGasSection(SeedEditorData data)
    {
        AddGasList(Loc.GetString("seed-editor-section-consumed-gases"), data.ConsumeGasses);
        AddGasList(Loc.GetString("seed-editor-section-exuded-gases"), data.ExudeGasses);
    }

    private void AddGasList(string title, Dictionary<Gas, float> gases)
    {
        var section = AddSection(title);
        var grid = NewGrid(3);
        foreach (var gas in gases.Keys.OrderBy(g => g.ToString()).ToList())
        {
            grid.AddChild(new Label { Text = gas.ToString(), MinWidth = 160 });
            grid.AddChild(NumberEditor(gases[gas], value => gases[gas] = value));
            grid.AddChild(RemoveButton(() => gases.Remove(gas)));
        }

        section.AddChild(grid);

        var addRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
        var options = new OptionButton { MinWidth = 160 };
        var missing = Enum.GetValues<Gas>().Where(g => !gases.ContainsKey(g)).ToList();
        for (var i = 0; i < missing.Count; i++)
        {
            options.AddItem(missing[i].ToString(), i);
        }

        options.OnItemSelected += args => options.SelectId(args.Id);
        var add = new Button { Text = Loc.GetString("seed-editor-gas-add"), Disabled = missing.Count == 0 };
        add.OnPressed += _ =>
        {
            gases[missing[options.SelectedId]] = 1f;
            RebuildSections();
        };

        addRow.AddChild(options);
        addRow.AddChild(add);
        section.AddChild(addRow);
    }

    #endregion

    /// <summary>
    /// A text box for a number, which turns red while it does not hold a valid number.
    /// </summary>
    private static LineEdit NumberEditor(float value, Action<float> onChanged)
    {
        var edit = new LineEdit { Text = value.ToString(CultureInfo.InvariantCulture), MinWidth = 80 };
        edit.OnTextChanged += args =>
        {
            if (float.TryParse(args.Text, NumberStyles.Float, CultureInfo.InvariantCulture, out var parsed))
            {
                edit.ModulateSelfOverride = null;
                onChanged(parsed);
            }
            else
            {
                edit.ModulateSelfOverride = InvalidColor;
            }
        };
        return edit;
    }

    private Button RemoveButton(Action remove)
    {
        var button = new Button { Text = Loc.GetString("seed-editor-remove") };
        button.OnPressed += _ =>
        {
            remove();
            RebuildSections();
        };
        return button;
    }
}
